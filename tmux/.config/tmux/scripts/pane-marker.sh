#!/bin/sh
# pane-marker.sh - アクティブな pane の位置を、ステータスバー右端の4マスの色にして出す
#   Ghostty のシェーダー（~/.config/ghostty/shaders/pane-dim.glsl）がこの色を読み、
#   アクティブな pane の外側に薄い色を重ねる。マスはシェーダーが周りの色で塗りつぶして隠す
#
# Usage: pane-marker.sh <セル幅px> <セル高さpx> <列数> <行数> <paneの左> <paneの上> <paneの幅> <paneの高さ>
#   paneの左・上は画面の左上を0としたマス目（ステータスバーの行も含める）
#
# 各マスの色 #RRGGBB に3つずつ数値を入れる（どれも 0〜255）
# 横方向の値（列数・paneの左・paneの幅）は広い画面で 255 を超えるので、上位と下位の2つに分ける
#   1マス目: セル幅, 列数の上位, 列数の下位
#   2マス目: セル高さ, 行数, paneの上
#   3マス目: paneの左の上位, paneの左の下位, paneの高さ
#   4マス目: paneの幅の上位, paneの幅の下位, 目印（165）
# 右端から 1マス目・2マス目・3マス目・4マス目の順に並ぶよう、4→1 の順で出す

[ $# -eq 8 ] || exit 0
for n in "$@"; do
    case "$n" in '' | *[!0-9]*) exit 0 ;; esac
    [ "$n" -le 65535 ] || exit 0
done
# 1バイトで渡す値（セル幅・セル高さ・行数・paneの上・paneの高さ）
for n in "$1" "$2" "$4" "$6" "$8"; do
    [ "$n" -le 255 ] || exit 0
done

printf '#[bg=#%02x%02x%02x] #[bg=#%02x%02x%02x] #[bg=#%02x%02x%02x] #[bg=#%02x%02x%02x] ' \
    $(($7 / 256)) $(($7 % 256)) 165 \
    $(($5 / 256)) $(($5 % 256)) "$8" \
    "$2" "$4" "$6" \
    "$1" $(($3 / 256)) $(($3 % 256))
